param(
    [Parameter(Mandatory = $true)]
    [ValidateSet('recurring-db-pool', 'payment-latency', 'misleading-memory', 'healthy-baseline')]
    [string]$Name,
    [string]$ApiBaseUrl = 'http://localhost:8000'
)

$uri = "$ApiBaseUrl/api/v1/demo/scenarios/$Name/activate"
$result = Invoke-RestMethod -Method Post -Uri $uri
Write-Host "Scenario: $($result.scenario)"
Write-Host "State: $($result.state)"

if ($Name -ne 'healthy-baseline') {
    Write-Host 'Traffic: bounded checkout traffic generated by the scenario API'
}
